def is_ecommerce_related(item: dict) -> bool:
    """
    항목이 전자상거래와 관련 있는지 판별합니다.

    판별 로직:
    1. EXCLUDE_KEYWORDS 포함 → 즉시 제외
    2. STRONG_KEYWORDS 중 하나라도 포함 → 통과
    3. STRONG + WEAK 둘 다 없으면 → 제외
    """
    text = (
        (item.get("title") or "") + " " + (item.get("summary") or "")
    ).lower()

    # 1. 명시적 제외 키워드가 있으면 무조건 제외
    if any(kw.lower() in text for kw in EXCLUDE_KEYWORDS):
        return False

    # 2. 강한 키워드 하나라도 있으면 통과
    if any(kw.lower() in text for kw in STRONG_KEYWORDS):
        return True

    return False


def identify_affected_products(item: dict) -> list[str]:
    """
    법령 항목의 내용을 분석하여 영향받는 상품군 목록을 반환합니다.
    해당 없으면 빈 리스트를 반환합니다.
    """
    text = (
        (item.get("title") or "") + " " + (item.get("summary") or "")
    ).lower()

    matched = []
    for category, keywords in PRODUCT_CATEGORY_MAP.items():
        if any(kw.lower() in text for kw in keywords):
            matched.append(category)

    return matched


def filter_and_tag(items: list[dict]) -> list[dict]:
    """
    전자상거래 관련 항목만 필터링하고,
    각 항목에 'affected_products' 필드를 추가합니다.
    """
    result = []
    for item in items:
        if not is_ecommerce_related(item):
            continue
        item["affected_products"] = identify_affected_products(item)
        result.append(item)
    return result
